# demandreductioncircularity: new carrier concrete_waste
from __future__ import annotations

from typing import TYPE_CHECKING

import numpy as np

if TYPE_CHECKING:
    from zen_creator.model import Model

from zen_creator import AssumptionInformation
from zen_creator.elements import Carrier
from zen_creator.utils.attribute import Attribute


class ConcreteWaste(Carrier):
    """Concrete waste carrier class.

    Generated by concrete_demolishment_overproduction and used by
    concrete_fine_collection and cement_recycling.
    """

    name: str = "concrete_waste"

    def __init__(self, model: Model, power_unit: str = "tproduct/h"):
        super().__init__(model=model, power_unit=power_unit)

    def _set_availability_export_yearly(self) -> Attribute:
        """
        Return the yearly export availability of concrete waste.

        """
        attr = self.availability_export_yearly
        attr.set_data(
            default_value=np.inf,
            source=AssumptionInformation(
                description=(
                    "No yearly limit on the export of concrete waste"
                    " The hourly export availability keeps the default of 0. #Note to check"
                ),
            ),
        )
        return attr
