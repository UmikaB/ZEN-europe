# demandreductioncircularity: new carrier plastic_waste
from __future__ import annotations

from typing import TYPE_CHECKING

import numpy as np

if TYPE_CHECKING:
    from zen_creator.model import Model

from zen_creator import AssumptionInformation
from zen_creator.elements import Carrier
from zen_creator.utils.attribute import Attribute


class PlasticWaste(Carrier):
    """Plastic waste carrier class.

    Generated by overproduction_use_plastic and treated by mechanical and
    chemical recycling or incineration.
    """

    name: str = "plastic_waste"

    def __init__(self, model: Model, power_unit: str = "tproduct/h"):
        super().__init__(model=model, power_unit=power_unit)

    def _set_availability_export_yearly(self) -> Attribute:
        """
        Return the yearly export availability of plastic waste.

        """
        attr = self.availability_export_yearly
        attr.set_data(
            default_value=np.inf,
            source=AssumptionInformation(
                description=(
                    "No yearly limit on the export of plastic waste. "
                    " The hourly export availability keeps the default of 0, "
                    " so all plastic waste is recycled or incinerated." #todo: check this!
                ),
            ),
        )
        return attr
